export function buildNetWorthSeries(
  currentNetWorth: number,
  currentCash: number,
  currentInvestments: number,
  timeframe: TimeframeOption
): NetWorthPoint[] {
  const templates: Record<TimeframeOption, { label: string; dateLabel: string; offset: number }[]> = {
    '1M': [
      { label: 'Oct 24', dateLabel: 'Oct 24, 2026', offset: -3420 },
      { label: 'Oct 31', dateLabel: 'Oct 31, 2026', offset: -2980 },
      { label: 'Nov 04', dateLabel: 'Nov 4, 2026', offset: -1650 },
      { label: 'Nov 09', dateLabel: 'Nov 9, 2026', offset: -1940 },
      { label: 'Nov 14', dateLabel: 'Nov 14, 2026', offset: -1120 },
      { label: 'Nov 18', dateLabel: 'Nov 18, 2026', offset: -640 },
      { label: 'Today', dateLabel: 'Nov 21, 2026', offset: 0 },
    ],
    '3M': [
      { label: 'Aug 24', dateLabel: 'Aug 24, 2026', offset: -9480 },
      { label: 'Sep 08', dateLabel: 'Sep 8, 2026', offset: -8120 },
      { label: 'Sep 22', dateLabel: 'Sep 22, 2026', offset: -6450 },
      { label: 'Oct 06', dateLabel: 'Oct 6, 2026', offset: -5100 },
      { label: 'Oct 20', dateLabel: 'Oct 20, 2026', offset: -3890 },
      { label: 'Nov 05', dateLabel: 'Nov 5, 2026', offset: -1750 },
      { label: 'Today', dateLabel: 'Nov 21, 2026', offset: 0 },
    ],
    '6M': [
      { label: 'Jun', dateLabel: 'Jun 2026', offset: -17600 },
      { label: 'Jul', dateLabel: 'Jul 2026', offset: -14300 },
      { label: 'Aug', dateLabel: 'Aug 2026', offset: -11850 },
      { label: 'Sep', dateLabel: 'Sep 2026', offset: -8400 },
      { label: 'Oct', dateLabel: 'Oct 2026', offset: -4200 },
      { label: 'Nov', dateLabel: 'Nov 21, 2026', offset: 0 },
    ],
    '1Y': [
      { label: 'Dec', dateLabel: 'Dec 2025', offset: -32400 },
      { label: 'Feb', dateLabel: 'Feb 2026', offset: -27900 },
      { label: 'Apr', dateLabel: 'Apr 2026', offset: -22100 },
      { label: 'Jun', dateLabel: 'Jun 2026', offset: -17600 },
      { label: 'Aug', dateLabel: 'Aug 2026', offset: -11850 },
      { label: 'Oct', dateLabel: 'Oct 2026', offset: -4200 },
      { label: 'Nov', dateLabel: 'Nov 21, 2026', offset: 0 },
    ],
  };

  return templates[timeframe].map((pt) => {
    const value = Math.max(0, currentNetWorth + pt.offset);
    const ratio = currentNetWorth > 0 ? value / currentNetWorth : 1;
    return {
      label: pt.label,
      dateLabel: pt.dateLabel,
      value,
      cash: Math.max(0, Math.round(currentCash * ratio)),
      investments: Math.max(0, Math.round(currentInvestments * ratio)),
    };
  });
}
